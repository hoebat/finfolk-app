import assert from 'node:assert/strict';
import {summary} from '../scripts/build_beach_summaries.mjs';
import {capabilities,searchBeaches,findJourney,categories} from '../web/discovery.js';
const line=(depth,y)=>({properties:{depth_m:depth,datum_label:'AHD'},geometry:{type:'LineString',coordinates:[[0,y],[.02,y]]}});
assert.deepEqual(capabilities({rasters:[]},[]),{raster:false,contours:false,measure:false,fine:false});
assert.equal(capabilities({rasters:[]},[line(10,0)]).measure,true);
assert.equal(capabilities({rasters:[{resolution_m:5,quality:'measured'}]}).fine,true);
const beach={id:'a',name:'Alpha',group:'Bay',region:'one',state:'Victoria',region_name:'First region',point:[.01,0],aliases:['Old name']};
const b={...beach,id:'b',name:'Beta',region:'two',state:'New South Wales',region_name:'Jervis Bay',aliases:[]};
const catalog={beaches:[beach,b]},region={contours:{datum:'AHD',survey_date:'2018'}};
const s=summary(beach,region,[line(5,-.001),line(10,-.002),line(15,-1)]);
assert.ok(s.depths[10].distance_m>200&&s.depths[10].distance_m<230);assert.equal(s.depths[15].status,'outside-radius');assert.equal(s.depths[20].status,'unavailable');
const summaries={beaches:[s]},filters={query:'',depth:10,sort:'depth'};
assert.deepEqual(searchBeaches(catalog,summaries,{},filters).map(b=>b.id),['a','b']);
assert.equal(searchBeaches(catalog,summaries,{}, {...filters,query:'Jervis'}).length,1);
assert.equal(searchBeaches(catalog,summaries,{}, {...filters,distance:500}).length,1);
assert.equal(searchBeaches(catalog,summaries,{}, {...filters,query:'old name'}).length,1);
assert.ok(categories(beach,s).includes('10 m contour within 250 m'));
const j={beach_id:'a',origin_id:'hub',date:'2026-10-31',trip_type:'day',status:'available',walk_verified:true,walk_max_leg_min:20,walking_min:25,transfers:1,outbound_min:90,valid_until:'2026-10-31',return:{}};
const jf={origin:'hub',date:j.date,trip:'day',walk:'30',sort:'fastest'};
assert.equal(findJourney({journeys:[j]},beach,jf,new Date('2026-10-27')),j);
assert.equal(findJourney({journeys:[j]},beach,{...jf,walk:'15'},new Date('2026-10-27')),null);
assert.equal(findJourney({journeys:[j]},beach,jf,new Date('2026-11-01')),null);
assert.equal(findJourney({journeys:[{...j,walk_verified:false}]},beach,jf,new Date('2026-10-27')),null);
console.log('Discovery checks passed: capability visibility, global search, absent depth handling, summary geometry, transport filters and expiry.');
