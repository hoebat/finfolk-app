"""Generate bundled beach-thumbnail outlines: python -m scripts.build_state_outlines.

Uses the same ABS 2021 GDA94 source as the coastal browsing boundaries. The
download is needed only to regenerate this committed asset, never at app build
or browser runtime. Coordinates retain their geographic meaning for dynamic dots.
"""
import argparse
import hashlib
import io
import json
import math
import zipfile
from pathlib import Path

import shapefile
from shapely.geometry import shape
from shapely.ops import unary_union

from depth_explorer.area_boundaries import download_territories, TERRITORY_SOURCE_URL

ROOT = Path(__file__).resolve().parents[1]
STATE_IDS = dict(zip("12345678", ["NSW", "VIC", "QLD", "SA", "WA", "TAS", "NT", "ACT"]))


def outline(geometry, name, label):
    west, south, east, north = geometry.bounds
    # About a fraction of a pixel at thumbnail size; preserve island topology.
    tolerance = max(east - west, north - south) / 700
    simplified = geometry.simplify(tolerance, preserve_topology=True)
    parts = list(simplified.geoms) if simplified.geom_type == "MultiPolygon" else [simplified]
    rings = []
    for part in parts:
        # Sub-pixel specks add considerable path data without visible context.
        if part.area < tolerance * tolerance:
            continue
        rings.extend([[[round(x, 5), round(y, 5)] for x, y in ring.coords]
                      for ring in [part.exterior, *part.interiors]])
    if not rings:
        raise ValueError(f"No visible outline for {name}")
    points = [point for ring in rings for point in ring]
    return {"name": name, "label": label, "rings": rings,
            "bounds": [min(p[0] for p in points), min(p[1] for p in points),
                       max(p[0] for p in points), max(p[1] for p in points)]}


def generate(archive):
    outlines = {}
    with zipfile.ZipFile(archive) as source:
        def component(suffix):
            return io.BytesIO(source.read(next(name for name in source.namelist() if name.endswith(suffix))))
        reader = shapefile.Reader(shp=component(".shp"), shx=component(".shx"), dbf=component(".dbf"))
        try:
            for record in reader.iterShapeRecords():
                if record.shape.shapeType == 0:
                    continue
                code, name = record.record["STE_CODE21"], record.record["STE_NAME21"]
                geometry = shape(record.shape.__geo_interface__)
                if code in STATE_IDS:
                    state_id = STATE_IDS[code]
                    outlines[state_id] = outline(geometry, name, state_id)
                elif code == "9":
                    # Separate distant groups rather than spanning half an ocean.
                    groups = {key: [] for key in ["JBT", "CC", "CX", "NF"]}
                    for part in geometry.geoms:
                        lon = part.representative_point().x
                        key = "CC" if lon < 100 else "CX" if lon < 110 else "JBT" if lon < 155 else "NF"
                        groups[key].append(part)
                    names = {"JBT": "Jervis Bay Territory", "CC": "Cocos (Keeling) Islands",
                             "CX": "Christmas Island", "NF": "Norfolk Island"}
                    for key, parts in groups.items():
                        outlines[key] = outline(unary_union(parts), names[key], key)
        finally:
            reader.close()
    if len(outlines) != 12:
        raise ValueError("Expected eight states/territories and four Other Territories groups")
    for item in outlines.values():
        if not all(math.isfinite(value) for value in item["bounds"]):
            raise ValueError("Non-finite outline bounds")
    return outlines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="Previously downloaded ABS state/territory ZIP")
    parser.add_argument("--output", type=Path, default=ROOT / "web/state-outlines.js")
    args = parser.parse_args()
    archive = args.source or download_territories(ROOT / ".cache/area-boundaries")
    outlines = generate(archive)
    source = {"name": "ABS States and Territories 2021", "url": TERRITORY_SOURCE_URL,
              "licence": "CC BY 4.0", "attribution": "© Australian Bureau of Statistics, simplified by FinFolk",
              "sha256": hashlib.sha256(archive.read_bytes()).hexdigest(), "crs": "EPSG:4283"}
    compact = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    args.output.write_text("// Generated by python -m scripts.build_state_outlines; do not hand-edit.\n"
                           "// Approximate geographic context, not legal boundaries or navigation data.\n"
                           f"export const OUTLINE_SOURCE={compact(source)};\n"
                           f"export const STATE_OUTLINES={compact(outlines)};\n")
    print(f"Generated {len(outlines)} outlines: {args.output.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
